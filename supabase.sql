-- =========================================================
-- SISTEM JURNAL MENGAJI MI - SKEMA DATABASE SUPABASE
-- =========================================================

-- 1. Tabel Pengguna (Admin & Guru)
CREATE TABLE IF NOT EXISTS public.roodoh_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE,
  password text NOT NULL,
  role text NOT NULL CHECK (role IN ('admin', 'guru')),
  nama text NOT NULL,
  jabatan text,
  assigned_classes jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 2. Tabel Kelas
CREATE TABLE IF NOT EXISTS public.roodoh_classes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama text NOT NULL UNIQUE,
  tingkat int4 NOT NULL,
  guru_pembimbing text,
  wali_kelas text,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Tabel Siswa
CREATE TABLE IF NOT EXISTS public.roodoh_students (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nisn text NOT NULL UNIQUE,
  nama text NOT NULL,
  kelas text NOT NULL,
  jenis_kelamin text,
  guru_pembimbing text,
  nama_wali text,
  juz30_tuntas_baseline boolean NOT NULL DEFAULT false,
  catatan_semester text,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 4. Tabel Jurnal Mengaji Harian
CREATE TABLE IF NOT EXISTS public.jurnal_ngaji (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  siswa_id int8 NOT NULL REFERENCES public.roodoh_students(id) ON DELETE CASCADE,
  tanggal date NOT NULL DEFAULT CURRENT_DATE,
  kehadiran text NOT NULL,
  jenis_bacaan text,
  detail_bacaan text,
  nilai_bacaan text,
  kategori_hafalan text,
  nama_surat text,
  ayat_hafalan text,
  nilai_hafalan text,
  catatan_guru text,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 5. Index Urutan Terbaru & Pencarian Siswa
CREATE INDEX IF NOT EXISTS idx_jurnal_ngaji_terbaru
  ON public.jurnal_ngaji (tanggal DESC, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_jurnal_ngaji_siswa
  ON public.jurnal_ngaji (siswa_id);

-- 6. Hak Akses Schema & Kebijakan RLS untuk Client App
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT ALL ON TABLE public.roodoh_users, public.roodoh_classes, public.roodoh_students, public.jurnal_ngaji TO anon, authenticated;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

ALTER TABLE public.roodoh_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.roodoh_classes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.roodoh_students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jurnal_ngaji ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "akses_roodoh_users" ON public.roodoh_users;
CREATE POLICY "akses_roodoh_users" ON public.roodoh_users
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "akses_roodoh_classes" ON public.roodoh_classes;
CREATE POLICY "akses_roodoh_classes" ON public.roodoh_classes
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "akses_roodoh_students" ON public.roodoh_students;
CREATE POLICY "akses_roodoh_students" ON public.roodoh_students
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "akses_jurnal_ngaji" ON public.jurnal_ngaji;
CREATE POLICY "akses_jurnal_ngaji" ON public.jurnal_ngaji
  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

